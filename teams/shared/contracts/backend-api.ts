/**
 * Backend API contract: request bodies (zod, validated by the server) and
 * response shapes for every /api/dojo endpoint. Paths: ./api-routes.ts.
 *
 * OWNER: BACKEND TEAM publishes it; Frontend and Game call against it.
 *
 * Every JSON response is `{ success: true, ...data }` or
 * `{ success: false, errorCode, error }`. `error` is a German message you can
 * show to the user. Error codes: UNAUTHENTICATED (401), FORBIDDEN (403),
 * NOT_FOUND (404), INVALID_REQUEST (400), CONFLICT (409), OFF_TOPIC (422),
 * RATE_LIMITED (429), INTERNAL_ERROR (500).
 */
import { z } from 'zod';

// ---------------------------------------------------------------------------
// Auth (Kahoot-style: teachers log in, students join a class with a PIN)
// ---------------------------------------------------------------------------

export const TeacherSignupBody = z.object({
  email: z.string().trim().toLowerCase().email().max(200),
  password: z.string().min(8).max(200),
  displayName: z.string().trim().min(1).max(60),
});

export const TeacherLoginBody = z.object({
  email: z.string().trim().toLowerCase().email().max(200),
  password: z.string().min(1).max(200),
});

export const StudentJoinBody = z.object({
  pin: z.string().regex(/^\d{6}$/),
  nickname: z.string().trim().min(1).max(30),
});

export type UserRole = 'teacher' | 'student';

/** `GET /me`, and the `user` field of every auth response. */
export interface Me {
  id: string;
  role: UserRole;
  displayName: string;
  /** The student's class; null for teachers. */
  classId: string | null;
  xp: number;
  level: number;
}

